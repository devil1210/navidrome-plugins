"""
ListenBrainz Missing Tracks Notifier for Navidrome & MediaHuman
==============================================================

Monitors Navidrome playlists generated by the ListenBrainz Daily Playlist plugin,
extracts tracks missing from the local library ('Tracks not matched'),
resolves the official full albums on YouTube Music, and sends the links to
Telegram formatted in a single blockquote for 1-click copying into
MediaHuman YouTube Downloader or direct server downloads via yt-dlp.
"""

